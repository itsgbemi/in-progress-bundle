export const TYPEFACE_OPTIONS: FontItem[] = ALL_FONTS;

export const INTERFACE_FONTS: FontItem[] = ALL_FONTS.filter(
(f) => f.weights && f.weights.length >= 3 && f.weights.includes(300)
);

export function findFontByIdOrName(query: string | undefined | null): FontItem | undefined {
if (!query) return undefined;
const q = query.toLowerCase().trim();
return ALL_FONTS.find(
(f) =>
f.id.toLowerCase() === q ||
f.name.toLowerCase() === q ||
f.family.toLowerCase().includes(`'${q}'`) ||
f.family.toLowerCase().includes(`"${q}"`)
);
}
